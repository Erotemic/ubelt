#!/usr/bin/env python
"""Generate the compact reference and mirror it into the installed package.

Run from any directory with Python >= 3.10. No optional dependencies needed.
The source of truth for API descriptions is the public Python API. Edit the
cookbook separately, then regenerate before release.

    python dev/maintain/generate_llm_docs.py
    python dev/maintain/generate_llm_docs.py --check
"""

import argparse
import inspect
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
import ubelt as ub  # noqa: E402

DOCS_URL = 'https://ubelt.readthedocs.io/en/latest/'


def summary(obj):
    """Extract the first prose paragraph of a docstring."""
    doc = inspect.getdoc(obj) or ''
    paragraph = doc.split('\n\n', 1)[0]
    return ' '.join(paragraph.split())


def signature(obj):
    try:
        return str(inspect.signature(obj))
    except (TypeError, ValueError):
        return ''


def reference():
    lines = [
        f'# Ubelt {ub.__version__}: compact public API reference',
        '',
        'Generated by dev/maintain/generate_llm_docs.py. Do not edit directly.',
        'Use `import ubelt as ub`. Signatures and summaries reflect this',
        'source snapshot. See the cookbook and full docstrings for detailed',
        'semantics, examples, and caveats. Methods inherited from the Python',
        'standard library are not enumerated here.',
        '',
    ]
    for name in sorted(ub.__all__):
        obj = getattr(ub, name)
        lines.extend([f'## ub.{name}', ''])
        canonical = getattr(obj, '__name__', '')
        if canonical != name and canonical in ub.__all__ and getattr(
            ub, canonical
        ) is obj:
            lines.append(f'Alias of `ub.{canonical}`.')
        elif inspect.ismodule(obj):
            lines.append(f'Module `{obj.__name__}`.')
        elif callable(obj):
            module = getattr(obj, '__module__', '')
            if not module.startswith('ubelt.'):
                lines.append(f'Standard-library alias: `{module}.{canonical}`.')
            else:
                sig = signature(obj)
                lines.append(f'`ub.{name}{sig}`')
                if not sig:
                    lines.append('See the class docstring for constructor usage.')
                if summary(obj):
                    lines.extend(['', summary(obj)])
                lines.extend(['', f'Implementation: `{module}.{canonical}`.'])
                if inspect.isclass(obj):
                    methods = {}
                    for base in obj.__mro__:
                        if not base.__module__.startswith('ubelt.'):
                            continue
                        for attr, member in vars(base).items():
                            if attr.startswith('_') or attr in methods:
                                continue
                            if isinstance(member, (staticmethod, classmethod)):
                                member = member.__func__
                            if inspect.isfunction(member) or isinstance(
                                member, property
                            ):
                                methods[attr] = member
                    if methods:
                        lines.extend(['', 'Public methods and properties:'])
                        for attr, member in sorted(methods.items()):
                            if isinstance(member, property):
                                spec = f'{attr} (property)'
                            else:
                                spec = attr + signature(member)
                            desc = summary(member)
                            lines.append(f'- `{spec}`' + (f': {desc}' if desc else ''))
        else:
            lines.append('Public constant or sentinel. See its defining module.')
        lines.append('')
    return '\n'.join(lines)


def index():
    return textwrap.dedent(f'''\
        # Ubelt

        > A lightweight Python utility belt with a standard-library-like feel,
        > including subprocess execution, hashing, caching, paths, collection
        > operations, and debugging utilities. This reference covers {ub.__version__}.

        Install `ubelt` and use `import ubelt as ub`. Prefer an existing utility
        when its semantics fit the task; use the standard library otherwise.

        ## Documentation

        - [Task-oriented cookbook](cookbook.md): common tasks, runnable examples, and caveats.
        - [Compact API reference](llms-full.txt): public symbols and signatures.
        - [Full documentation]({DOCS_URL}): detailed contracts and examples.
        - [Source repository](https://github.com/Erotemic/ubelt): implementation and tests.

        ## Important boundaries

        - `hash_data` uses a legacy structured encoding with known ambiguities.
          It is not a collision-resistant encoding of structured objects.
        - Only load pickle caches from trusted sources. `Cacher` also supports JSON.
        - Use `cmd(..., check=True)` when a nonzero exit code is an error.
        - General-purpose atomic file I/O is outside ubelt's scope; see [safer](https://pypi.org/project/safer/).
        - Use standard `pathlib.Path` when sufficient; `ub.Path` adds useful
          extensions but some overlapping methods have different contracts.
        - Prefer current APIs in the cookbook to deprecated or legacy spellings.
        ''')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check for stale files')
    args = parser.parse_args()
    docs = {
        'llms.txt': index(),
        'llms-full.txt': reference(),
        'cookbook.md': (ROOT / 'cookbook.md').read_text(encoding='utf-8'),
    }
    stale = []
    for name, content in docs.items():
        # The cookbook is hand-maintained; do not rewrite its source.
        targets = [ROOT / 'ubelt' / '_docs' / name]
        if name != 'cookbook.md':
            targets.append(ROOT / name)
        for path in targets:
            if args.check:
                if not path.exists() or path.read_text(encoding='utf-8') != content:
                    stale.append(str(path.relative_to(ROOT)))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding='utf-8', newline='\n')
    if stale:
        parser.exit(1, 'Stale LLM documentation: ' + ', '.join(stale) + '\n')


if __name__ == '__main__':
    main()
